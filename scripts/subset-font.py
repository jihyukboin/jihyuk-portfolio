"""Generate the common-character font; requires fonttools[woff] and Pretendard 1.3.9."""

from pathlib import Path
import sys

from fontTools import subset
from fontTools.ttLib import TTFont


root = Path(__file__).resolve().parent.parent
font_dir = root / "src/app/fonts/pretendard/1.3.9"
font = TTFont(sys.argv[1], recalcTimestamp=False)
characters = set(range(0x20, 0x7F))
for path in (root / "src").rglob("*"):
    if path.suffix in {".ts", ".tsx", ".mts", ".md"}:
        characters.update(map(ord, path.read_text()))
characters.intersection_update(font.getBestCmap())

options = subset.Options()
options.flavor = "woff2"
subsetter = subset.Subsetter(options=options)
subsetter.populate(unicodes=characters)
subsetter.subset(font)
font.flavor = "woff2"
font.save(font_dir / "pretendard-common.woff2")

unicode_range = ", ".join(f"U+{value:X}" for value in sorted(characters))
(font_dir / "pretendard-common.css").write_text(
    "/* Generated by scripts/subset-font.py from Pretendard 1.3.9 (SIL OFL). */\n"
    "/* Keep after the original subsets so common characters use this face. */\n"
    "@font-face {\n"
    "  font-family: 'Pretendard Variable';\n"
    "  font-style: normal;\n"
    "  font-display: swap;\n"
    "  font-weight: 45 920;\n"
    "  src: url('./pretendard-common.woff2') format('woff2');\n"
    f"  unicode-range: {unicode_range};\n"
    "}\n"
)
print(f"Generated common variable font with {len(characters)} characters")
